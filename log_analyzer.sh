
#!/bin/bash

# Linux System Log Analyzer
# Analyzes errors and warnings using systemd journal

# ---------------- CONFIGURATION ----------------

REPORT_DIR="$HOME/log_reports"
REPORT_DATE=$(date '+%Y%m%d_%H%M%S')
REPORT_FILE="$REPORT_DIR/log_report_$REPORT_DATE.txt"

# ---------------- CHECK REQUIREMENTS ----------------

if ! command -v journalctl &>/dev/null; then
    echo "[ERROR] journalctl is not installed."
    exit 1
fi

if ! journalctl -n 1 --no-pager &>/dev/null; then
    echo "[ERROR] Cannot access system journal."
    echo "Try running the script with sudo."
    exit 1
fi

# ---------------- SELECT TIME RANGE ----------------

echo "=================================================="
echo "              LINUX LOG ANALYZER"
echo "=================================================="
echo
echo "Select Log Analysis Period:"
echo
echo "1. Current Boot"
echo "2. Last 24 Hours"
echo "3. Last 7 Days"
echo

read -rp "Enter your choice [1-3]: " CHOICE

case "$CHOICE" in
    1)
        TIME_FILTER=(-b)
        PERIOD="Current Boot"
        ;;
    2)
        TIME_FILTER=(--since "24 hours ago")
        PERIOD="Last 24 Hours"
        ;;
    3)
        TIME_FILTER=(--since "7 days ago")
        PERIOD="Last 7 Days"
        ;;
    *)
        echo "[ERROR] Invalid selection."
        exit 1
        ;;
esac

# ---------------- CREATE REPORT DIRECTORY ----------------

if ! mkdir -p "$REPORT_DIR"; then
    echo "[ERROR] Unable to create report directory."
    exit 1
fi

# ---------------- GENERATE REPORT ----------------

{
    echo "=================================================="
    echo "              LINUX LOG ANALYSIS REPORT"
    echo "=================================================="
    echo "Hostname       : $(hostname)"
    echo "Analysis Date  : $(date '+%Y-%m-%d %H:%M:%S')"
    echo "Analysis Period: $PERIOD"
    echo "Generated By   : $(whoami)"
    echo "=================================================="

    # ERROR ANALYSIS

    echo
    echo "========== ERROR LOGS =========="

    ERROR_COUNT=$(journalctl "${TIME_FILTER[@]}" -p err..err \
        --no-pager -q 2>/dev/null | wc -l)

    echo "Total Errors: $ERROR_COUNT"
    echo
    echo "Latest 10 Errors:"
    echo

    journalctl "${TIME_FILTER[@]}" -p err..err \
        -n 10 --no-pager -q 2>/dev/null

    # WARNING ANALYSIS

    echo
    echo "========== WARNING LOGS =========="

    WARNING_COUNT=$(journalctl "${TIME_FILTER[@]}" -p warning..warning \
        --no-pager -q 2>/dev/null | wc -l)

    echo "Total Warnings: $WARNING_COUNT"
    echo
    echo "Latest 10 Warnings:"
    echo

    journalctl "${TIME_FILTER[@]}" -p warning..warning \
        -n 10 --no-pager -q 2>/dev/null

    # SUMMARY

    echo
    echo "=================================================="
    echo "                ANALYSIS SUMMARY"
    echo "=================================================="

    printf "Total Errors   : %s\n" "$ERROR_COUNT"
    printf "Total Warnings : %s\n" "$WARNING_COUNT"

    echo
    echo "Log Analysis Completed."
    echo "=================================================="

} | tee "$REPORT_FILE"

# ---------------- FINAL STATUS ----------------

if [[ ${PIPESTATUS[0]} -eq 0 ]]; then
    echo
    echo "[SUCCESS] Report saved successfully."
    echo "Location: $REPORT_FILE"
else
    echo
    echo "[ERROR] Report generation failed."
    exit 1
fi
