
#!/bin/bash

# Linux Failed Login Report
# Identifies failed authentication attempts using systemd journal

# ---------------- CONFIGURATION ----------------

REPORT_DIR="$HOME/security_reports"
REPORT_DATE=$(date '+%Y%m%d_%H%M%S')
REPORT_FILE="$REPORT_DIR/failed_login_report_$REPORT_DATE.txt"

# ---------------- CHECK REQUIREMENTS ----------------

if ! command -v journalctl &>/dev/null; then
    echo "[ERROR] journalctl is not available."
    exit 1
fi

if ! journalctl -n 1 --no-pager &>/dev/null; then
    echo "[ERROR] Cannot access system journal."
    echo "Try running the script with sudo."
    exit 1
fi

# ---------------- SELECT TIME RANGE ----------------

echo "=================================================="
echo "           FAILED LOGIN SECURITY REPORT"
echo "=================================================="
echo
echo "Select Analysis Period:"
echo
echo "1. Current Boot"
echo "2. Last 24 Hours"
echo "3. Last 7 Days"
echo

read -rp "Enter your choice [1-3]: " CHOICE

case "$CHOICE" in
    1)
        TIME_FILTER=(-b)
        PERIOD="Current Boot"
        ;;
    2)
        TIME_FILTER=(--since "24 hours ago")
        PERIOD="Last 24 Hours"
        ;;
    3)
        TIME_FILTER=(--since "7 days ago")
        PERIOD="Last 7 Days"
        ;;
    *)
        echo "[ERROR] Invalid selection."
        exit 1
        ;;
esac

# ---------------- CREATE REPORT DIRECTORY ----------------

if ! mkdir -p "$REPORT_DIR"; then
    echo "[ERROR] Cannot create report directory."
    exit 1
fi

# ---------------- COLLECT FAILED LOGINS ----------------

FAILED_LOGS=$(
    journalctl "${TIME_FILTER[@]}" --no-pager -o short-iso 2>/dev/null |
    grep -Ei 'Failed password|Failed publickey|authentication failure|authentication failed' || true
)

FAILED_COUNT=$(printf '%s\n' "$FAILED_LOGS" | grep -c .)

# ---------------- GENERATE REPORT ----------------

{
    echo "=================================================="
    echo "           FAILED LOGIN SECURITY REPORT"
    echo "=================================================="
    echo "Hostname        : $(hostname)"
    echo "Analysis Date   : $(date '+%Y-%m-%d %H:%M:%S')"
    echo "Analysis Period : $PERIOD"
    echo "Generated By    : $(whoami)"
    echo "=================================================="

    # FAILED LOGIN SUMMARY

    echo
    echo "========== FAILED AUTHENTICATION SUMMARY =========="
    echo
    echo "Total Failed Authentication Log Entries: $FAILED_COUNT"

    # FAILED LOGIN DETAILS

    echo
    echo "========== FAILED LOGIN DETAILS =========="
    echo

    if [[ -n "$FAILED_LOGS" ]]; then
        printf '%s\n' "$FAILED_LOGS"
    else
        echo "No failed authentication entries found."
    fi

    # SOURCE IP ANALYSIS

    echo
    echo "========== SOURCE IP ANALYSIS =========="
    echo
    echo "Failed authentication entries by source IP:"
    echo

    if [[ -n "$FAILED_LOGS" ]]; then
        printf '%s\n' "$FAILED_LOGS" |
        awk '{
            for (i=1; i<=NF; i++) {
                if ($i == "from" && $(i+1) ~ /^[0-9a-fA-F:.]+$/)
                    print $(i+1)
                else if ($i ~ /^rhost=/) {
                    sub(/^rhost=/, "", $i)
                    if ($i != "" && $i != "-")
                        print $i
                }
            }
        }' |
        sort | uniq -c | sort -nr
    fi

    # USERNAME ANALYSIS

    echo
    echo "========== ATTEMPTED USERNAMES =========="
    echo
    echo "Failed authentication entries by username:"
    echo

    if [[ -n "$FAILED_LOGS" ]]; then
        printf '%s\n' "$FAILED_LOGS" |
        awk '{
            for (i=1; i<=NF; i++) {
                if ($i == "for") {
                    if ($(i+1) == "invalid" && $(i+2) == "user")
                        print $(i+3)
                    else if ($(i+1) != "")
                        print $(i+1)
                }

                if ($i ~ /^user=/) {
                    sub(/^user=/, "", $i)
                    if ($i != "" && $i != "-")
                        print $i
                }
            }
        }' |
        sort | uniq -c | sort -nr
    fi

    # FINAL SUMMARY

    echo
    echo "=================================================="
    echo "                 REPORT SUMMARY"
    echo "=================================================="
    echo "Analysis Period              : $PERIOD"
    echo "Failed Authentication Entries: $FAILED_COUNT"
    echo
    echo "Security Report Completed."
    echo "=================================================="

} | tee "$REPORT_FILE"

# ---------------- FINAL STATUS ----------------

if [[ ${PIPESTATUS[0]} -eq 0 ]]; then
    echo
    echo "[SUCCESS] Security report saved."
    echo "Location: $REPORT_FILE"
else
    echo
    echo "[ERROR] Report generation failed."
    exit 1
fi
